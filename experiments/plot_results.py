#!/usr/bin/env python3
"""
Generate publication-quality figures from PHE/VPK NeurIPS experiment results.

Loops over per-dataset result directories (experiments/results/<dataset>/)
and writes separate figures to experiments/figures/<dataset>/.

Figures per dataset:
  1  Noise tradeoff 1×3: recall vs noise, corpus size, top-K (Exp D + I + E)
  2  Algorithm comparison bar chart (Exp A)
  3  Radar: security · efficiency · fidelity (Exp A + attack model)

Supplementary:
  S1  Mean absolute cosine error vs. noise (Monte Carlo theory validation)
  S2  Score entropy vs. noise level (Exp D)

Also handles legacy flat layout (CSVs directly in experiments/results/).

Aggregation strategy (N=10 trials):
  - per-trial mean is computed first (30 queries → 1 scalar per trial)
  - uncertainty shown as shaded ±1σ river bands, not error bars
  - alpha=0.18 on bands so overlapping rivers blend transparently
"""

