# ── Discover datasets ────────────────────────────────────────────────────────

def discover_datasets() -> list[tuple[str, Path]]:
    """Find dataset result directories.

    Layout: results/<dataset>/<run-id>/exp_*.csv
    A 'latest' symlink in results/<dataset>/ always points to the most recent run.
    Also supports legacy flat layout (results/<dataset>/exp_*.csv).
    """
    datasets = []
    for ds_dir in sorted(RESULTS_ROOT.iterdir()):
        if not ds_dir.is_dir():
            continue
        # Prefer 'latest' symlink if present
        latest = ds_dir / "latest"
        if latest.is_symlink() and latest.is_dir() and any(latest.glob("exp_*.csv")):
            datasets.append((ds_dir.name, latest.resolve()))
        # Legacy flat layout: CSVs directly in results/<dataset>/
        elif any(ds_dir.glob("exp_*.csv")):
            datasets.append((ds_dir.name, ds_dir))

    # Legacy root-level flat layout
    if not datasets and any(RESULTS_ROOT.glob("exp_*.csv")):
        datasets.append(("legacy", RESULTS_ROOT))

    return datasets


