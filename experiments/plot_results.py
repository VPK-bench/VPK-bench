def plot_dataset(ds_tag: str, results_dir: Path, figs_dir: Path):
    """Generate all figures for one dataset."""
    print(f"\n{'─'*50}")
    print(f"  Dataset: {ds_title(ds_tag)}  ({ds_tag})")
    print(f"  Results: {results_dir}")
    print(f"  Figures: {figs_dir}")
    print(f"{'─'*50}")

    fig1_noise_tradeoff(results_dir, figs_dir, ds_tag)
    df_a = fig2_algorithm_comparison(results_dir, figs_dir, ds_tag)
    fig3_radar(results_dir, figs_dir, ds_tag, df_a=df_a)
    supp_fig1_cosine_error(figs_dir, ds_tag)
    supp_fig2_entropy(results_dir, figs_dir, ds_tag)
    emit_latex_labels(figs_dir)


def main():
    datasets = discover_datasets()
    if not datasets:
        print("No experiment results found in", RESULTS_ROOT)
        print("Run experiments first:  python experiments/run_experiments.py --exp A --dataset nfcorpus")
        sys.exit(1)

    print(f"Found {len(datasets)} dataset(s): {', '.join(tag for tag, _ in datasets)}")

    for ds_tag, results_dir in datasets:
        figs_dir = FIGS_ROOT if ds_tag == "legacy" else FIGS_ROOT / ds_tag
        plot_dataset(ds_tag, results_dir, figs_dir)

    print(f"\nAll figures saved under {FIGS_ROOT.resolve()}/")


if __name__ == "__main__":
    main()
