def fig2_algorithm_comparison(results_dir, figs_dir, ds_tag):
    path = results_dir / "exp_A_algorithm_comparison.csv"
    if not path.exists():
        print(f"  Fig 2: skipped (no {path.name})")
        return

    print(f"  Fig 2: Algorithm Comparison …")
    df_a = pd.read_csv(path)
    if "trial" not in df_a.columns:
        df_a["trial"] = 1

    present_algos = [a for a in ALGO_ORDER if a in df_a["algorithm"].unique()]

    recall_stats   = trial_stats(df_a, ["algorithm"], "recall_at_k").reindex(present_algos)
    enc_stats_raw  = trial_stats(df_a, ["algorithm"], "enc_encrypt_us").reindex(present_algos)
    srch_stats_raw = trial_stats(df_a, ["algorithm"], "enc_search_us").reindex(present_algos)

    recall_stats.index   = [SHORT[i] for i in recall_stats.index]
    enc_stats_raw.index  = [SHORT[i] for i in enc_stats_raw.index]
    srch_stats_raw.index = [SHORT[i] for i in srch_stats_raw.index]

    labels = list(recall_stats.index)
    x      = np.arange(len(labels))
    colors = [PALETTE[l] for l in labels]

    pt_recall = per_trial_means(df_a, ["algorithm"], "recall_at_k")
    pt_enc    = per_trial_means(df_a, ["algorithm"], "enc_encrypt_us")
    pt_srch   = per_trial_means(df_a, ["algorithm"], "enc_search_us")

    rng = np.random.default_rng(42)

    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))

    for ax, stats, pt_df, pt_col, ylabel, ylim, title, yscale, divisor in [
        (axes[0], recall_stats,   pt_recall, "recall_at_k",    "$R_{10}$",                       (0.97, 1.01), "(a) Recall for $k=10$",                  "linear", 1),
        (axes[1], enc_stats_raw,  pt_enc,    "enc_encrypt_us",  "$\\tau_{\\mathrm{enc}}$ (ms)",   None,         "(b) Encryption latency",                 "log",    1000),
        (axes[2], srch_stats_raw, pt_srch,   "enc_search_us",   "$\\tau_{\\mathrm{search}}$ (ms)",None,         "(c) Encrypted search latency",           "log",    1000),
    ]:
        mean_col = [c for c in stats.columns if c.endswith("_mean")][0]
        ax.bar(x, stats[mean_col] / divisor, color=colors, alpha=0.85, zorder=2)

        for xi, algo_label in zip(x, labels):
            algo_key = {v: k for k, v in SHORT.items()}[algo_label]
            pts = pt_df[pt_df["algorithm"] == algo_key][pt_col].values / divisor
            jitter = rng.uniform(-0.18, 0.18, size=len(pts))
            ax.scatter(xi + jitter, pts, color="white", s=18, zorder=4, alpha=0.9, linewidths=0)
            ax.scatter(xi + jitter, pts, color=PALETTE[algo_label], s=10, zorder=5,
                       alpha=0.7, linewidths=0)

        ax.set_xticks(x); ax.set_xticklabels(labels, rotation=30, ha="right")
        ax.set_ylabel(ylabel)
        ax.set_title(title)
        ax.set_yscale(yscale)
        if ylim:
            ax.set_ylim(*ylim)
        if yscale == "linear":

            ax.yaxis.set_major_formatter(mtick.FormatStrFormatter("%.2f"))
        else:
            ax.yaxis.set_major_formatter(mtick.FuncFormatter(
                lambda v, _: f"{v:.3f}" if v < 1 else f"{v:.1f}"))

    fig.tight_layout()
    save(fig, figs_dir, "fig2_algorithm_comparison")
    return df_a  # needed by fig3


def fig1_noise_tradeoff(results_dir, figs_dir, ds_tag):
    path_d = results_dir / "exp_D_noise_tradeoff.csv"
    path_i = results_dir / "exp_I_corpus_size_noise.csv"
    path_e = results_dir / "exp_E_topk_sensitivity.csv"
    if not path_d.exists():
        print(f"  Fig 1: skipped (no {path_d.name})")
        return

    print(f"  Fig 1: Noise–Security Tradeoff (1×3) …")
    df_d = pd.read_csv(path_d)
    if "trial" not in df_d.columns:
        df_d["trial"] = 1

    has_panel_b = path_i.exists()
    has_panel_c = path_e.exists()

    NOISE_ORDER = ["1%","5%","10%","20%","30%","50%","70%"]
    NOISE_X     = [1, 5, 10, 20, 30, 50, 70]
    D_ALGOS     = ["Noise","Combined","RomeCombined","RommCombined","CkksCombined"]

    fig, axes = plt.subplots(1, 3, figsize=(18, 4.5))

    # (a) Recall vs noise
    for algo in D_ALGOS:
        if algo not in df_d["algorithm"].unique():
            continue
        label = SHORT[algo]
        sub   = df_d[df_d["algorithm"] == algo]
        recall_ts = trial_stats(sub, ["noise_label"], "recall_at_k").reindex(NOISE_ORDER)
        river(axes[0], NOISE_X,
              recall_ts["recall_at_k_mean"], recall_ts["recall_at_k_std"],
              PALETTE[label], label, MARKERS[label])

    axes[0].set_xlabel("Noise magnitude $\\epsilon$ (%)")
    axes[0].set_ylabel("$R_{10}$")
    axes[0].set_ylim(0.82, 1.01)
    axes[0].set_title("(a) Recall vs. noise level ($k=10$)")
    axes[0].legend(fontsize=9, loc="upper right", framealpha=0.85)
    axes[0].yaxis.set_major_formatter(mtick.FormatStrFormatter("%.3f"))

    # (b) Corpus size × noise
    if has_panel_b:
        print(f"  Fig 1b: Corpus Size × Noise …")
        df_i = pd.read_csv(path_i)
        if "trial" not in df_i.columns:
            df_i["trial"] = 1

        I_NOISE_ORDER = ["0%","1%","10%","30%","50%","70%"]
        I_NOISE_X     = [0, 1, 10, 30, 50, 70]

        corpus_sizes = sorted(df_i["corpus_size"].unique())
        cmap = plt.cm.viridis(np.linspace(0.15, 0.85, len(corpus_sizes)))

        for size, color in zip(corpus_sizes, cmap):
            sub = df_i[df_i["corpus_size"] == size]
            ts  = trial_stats(sub, ["noise_label"], "recall_at_k").reindex(I_NOISE_ORDER)
            river(axes[1], I_NOISE_X, ts["recall_at_k_mean"], ts["recall_at_k_std"],
                  color, f"n={size:,}", "o")

        axes[1].set_xlabel("Noise magnitude $\\epsilon$ (%)")
        axes[1].set_ylabel("$R_{10}$ (DS+NI)")
        axes[1].set_ylim(0.82, 1.02)
        axes[1].set_title("(b) Recall vs. noise level by corpus size ($k=10$)")
        axes[1].legend(fontsize=9, loc="upper right", framealpha=0.85)
    else:
        axes[1].set_visible(False)

    # (c) Recall@K vs K
    if has_panel_c:
        print(f"  Fig 1c: Recall@K vs K …")
        df_e = pd.read_csv(path_e)
        if "trial" not in df_e.columns:
            df_e["trial"] = 1

        K_VALS = [1, 5, 10, 20, 50]
        TOPK_ALGOS = ["Noise","Combined","RomeCombined","RommCombined","Ckks","CkksCombined"]

        for algo in TOPK_ALGOS:
            if algo not in df_e["algorithm"].unique():
                continue
            label = SHORT[algo]
            sub   = df_e[df_e["algorithm"] == algo]
            ts    = trial_stats(sub, ["top_k"], "recall_at_k").reindex(K_VALS)
            river(axes[2], K_VALS,
                  ts["recall_at_k_mean"], ts["recall_at_k_std"],
                  PALETTE[label], label, MARKERS[label])

        axes[2].set_xlabel("$K$")
        axes[2].set_ylabel("$R_{K}$")
        axes[2].set_title("(c) Recall as a function of $K$")
        axes[2].set_xticks(K_VALS)
        axes[2].set_ylim(0.95, 1.001)
        axes[2].legend(fontsize=9, loc="lower right", framealpha=0.85)
    else:
        axes[2].set_visible(False)

    fig.tight_layout()
    save(fig, figs_dir, "fig1_noise_tradeoff")


