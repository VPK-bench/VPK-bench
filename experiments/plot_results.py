def emit_latex_labels(figs_dir):
    """Write a .tex file with \\newcommand definitions for figure labels."""
    tex_path = figs_dir / "figure_labels.tex"
    lines = [
        "% Auto-generated by plot_results.py — do not edit by hand.",
        "% Usage:  \\input{figure_labels.tex}",
        "%         As shown in \\cref{\\figAlgoComparison}, ...",
        "",
    ]
    for stem, cmd in LATEX_LABELS.items():
        lines.append(f"\\newcommand{{\\{cmd}}}{{fig:{stem}}}")
    tex_path.write_text("\n".join(lines) + "\n")
    print(f"  saved figure_labels.tex  →  {figs_dir}/")


# ── Helpers ───────────────────────────────────────────────────────────────────

def trial_stats(df, group_cols, value_col):
    """query→trial mean, then trial→(mean, std)."""
    per_trial = df.groupby(group_cols + ["trial"])[value_col].mean()
    return per_trial.groupby(group_cols).agg(
        **{f"{value_col}_mean": "mean",
           f"{value_col}_std":  "std"}
    )


def per_trial_means(df, group_cols, value_col):
    return df.groupby(group_cols + ["trial"])[value_col].mean().reset_index()


def river(ax, x, means, stds, color, label, marker, lw=2, ms=7, ls="-", zorder=2):
    means = np.asarray(means, dtype=float)
    stds  = np.asarray(stds,  dtype=float)
    ax.plot(x, means, color=color, linewidth=lw, markersize=ms,
            marker=marker, label=label, ls=ls, zorder=zorder)
    ax.fill_between(x, means - stds, means + stds,
                    color=color, alpha=RIVER_ALPHA, linewidth=0, zorder=zorder - 1)


def save(fig, figs_dir, name):
    figs_dir.mkdir(parents=True, exist_ok=True)
    for ext in ("png", "pdf"):
        fig.savefig(figs_dir / f"{name}.{ext}", bbox_inches="tight", dpi=300)
    print(f"  saved {name}.png / .pdf  →  {figs_dir}/")
    plt.close(fig)


